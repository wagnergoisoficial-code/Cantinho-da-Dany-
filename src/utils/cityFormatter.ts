const LOWERCASE_PARTICLES = new Set(['of', 'the', 'and', 'by', 'in', 'on', 'at']);

function stripDiacritics(str: string): string {
  return str.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

export function formatOfficialCityName(raw: string): string {
  const collapsed = raw.trim().replace(/\s+/g, ' ');
  if (!collapsed) return '';

  const lookupKey = stripDiacritics(collapsed).toLowerCase();
  if (OFFICIAL_CITY_MAP[lookupKey]) {
    return OFFICIAL_CITY_MAP[lookupKey];
  }

  // Fallback: Title Case respeitando abreviações comuns dos EUA e partículas
  const words = collapsed.split(' ');
  return words
    .map((word, index) => {
      const clean = stripDiacritics(word).toLowerCase();
      if (clean === 'st' || clean === 'st.') return 'St.';
      if (clean === 'ft' || clean === 'ft.') return 'Ft.';
      if (clean === 'mt' || clean === 'mt.') return 'Mt.';
      if (index > 0 && LOWERCASE_PARTICLES.has(clean)) {
        return clean;
      }
      if (clean.includes('-')) {
        return clean
          .split('-')
          .map((part, pIdx) =>
            pIdx > 0 && LOWERCASE_PARTICLES.has(part)
              ? part
              : part.charAt(0).toUpperCase() + part.slice(1)
          )
          .join('-');
      }
      return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
    })
    .join(' ');
}

